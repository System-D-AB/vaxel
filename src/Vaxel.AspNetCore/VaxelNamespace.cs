namespace Vaxel;

/// <summary>
/// Specifies the parser context for a patch fragment.
/// </summary>
public enum VaxelNamespace
{
    /// <summary>
    /// Standard HTML namespace (default).
    /// </summary>
    Html,

    /// <summary>
    /// SVG namespace (http://www.w3.org/2000/svg).
    /// </summary>
    Svg,

    /// <summary>
    /// MathML namespace (http://www.w3.org/1998/Math/MathML).
    /// </summary>
    MathMl
}
